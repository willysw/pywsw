__all__ = ("Overturning",)

from collections.abc import Iterable
from dataclasses import dataclass, field
from functools import cached_property

import numpy as np
from scipy.optimize import Bounds, OptimizeResult
from scipy.optimize import shgo as scipy_shgo

from pywsw.core import parse_as_ndarray

_1_6 = 1.0/6.0
_1_3 = 1.0/3.0
_1_2 = 1.0/2.0
_2_3 = 2.0/3.0


@dataclass(frozen=True)
class Overturning:
    """A immutable class representing a footing under overturning loads.

    All units are assumed to be consistent.

    Attributes
    ----------
    toe_length : float
    heel_length : float
    bearing_length : float
    height : float
    width : float
    overturning_moment : float
    superimposed_load : float
    toe_super_unit_load : float, optional
        Defaults to 0.0
    heel_super_unit_load : float, optional
        Defaults to 0.0
    unit_weight : float, optional
        Defaults to 150.0 (assuming lbf, ft, s)
    optimize_solution : scipy.optimize.OptimizeResult
        The raw optimization solution if one was generated by
        `Overturning.optimize()`, `None` otherwise.

    Properties
    ----------
    length : float
        Total footing length.
    safety_factor : float
        Safety Factor against overturning.
    bearing_pressure : (float, float)
        (Max, Min) bearing pressures. Returns (inf, -inf) if net soil
        bearing reaction is outside the footing.
    max_bearing_pressure : float
        Maximum bearing pressure.
    volume : float
        Volume of the footing.
    weight : float
        Weight of the footing without any superimposed loads.
    superimposed_weight : float
        Weight of all superimposed loads.
    total_weight : float
        Total self and superimposed weight.
    resisting_moment : float
        Resisting moment from all applied self and superimposed loads.
    reaction_offset_from_toe : float
        Distance from the toe to the net soil pressure reaction.
    eccentricity : float
        Distance from the footing centerline to the net soil pressure
        reaction. Positive values are towards the toe.
    relative_eccentricity : float
        Ratio of eccentricity to length. Values between -0.5 and 0.5 are
        within the footing. Values outside that imply infinite bearing pressure.
    outside_middle_third : bool
        Returns true if the net soil pressure reaction is within the middle
        third of the footing (i.e., no net uplift).
    outside_footing : bool
        Returns true if the net soil pressure reaction is outside of the footing.
    """
    toe_length: float
    heel_length: float
    bearing_length: float
    height: float
    width: float
    overturning_moment: float
    superimposed_load: float
    toe_super_unit_load: float = 0.0
    heel_super_unit_load: float = 0.0
    unit_weight: float = 150.0
    optimize_solution: OptimizeResult|None = field(default=None, repr=False)

    """''''''''''''''''"""
    """   PROPERTIES   """
    """''''''''''''''''"""

    @cached_property
    def length(self) -> float:
        return self.toe_length + self.bearing_length + self.heel_length

    @cached_property
    def safety_factor(self) -> float:
        return self.calc_stability(
            l_t=self.toe_length,
            l_h=self.heel_length,
            l_brg=self.bearing_length,
            h=self.height,
            b=self.width,
            M_ot=self.overturning_moment,
            W=self.superimposed_load,
            w_t=self.toe_super_unit_load,
            w_h=self.heel_super_unit_load,
            gamma_c=self.unit_weight
        )

    @cached_property
    def bearing_pressure(self) -> tuple[float, float]:
        return self.calc_bearing(
            l_t=self.toe_length,
            l_h=self.heel_length,
            l_brg=self.bearing_length,
            h=self.height,
            b=self.width,
            M_ot=self.overturning_moment,
            W=self.superimposed_load,
            w_t=self.toe_super_unit_load,
            w_h=self.heel_super_unit_load,
            gamma_c=self.unit_weight
        )

    @cached_property
    def max_bearing_pressure(self) -> float:
        return self.bearing_pressure[0]

    @cached_property
    def volume(self) -> float:
        return (
            self.width
            * self.height
            * self.length
        )

    @cached_property
    def weight(self) -> float:
        return self.volume*self.unit_weight

    @cached_property
    def superimposed_weight(self) -> float:
        return (
            self.superimposed_load
            + self.width * (
                self.toe_length*self.toe_super_unit_load
                + self.heel_length*self.heel_super_unit_load
            )
        )

    @cached_property
    def total_weight(self) -> float:
        return self.weight + self.superimposed_weight

    @cached_property
    def resisting_moment(self) -> float:
        # Resisting Moment
        mr = (
            # Toe surcharge moment
            _1_2*self.width*self.toe_super_unit_load*self.toe_length**2,
            # Super load moment
            self.superimposed_load*(self.toe_length + _1_2*self.bearing_length),
            # Heel surcharge moment
            _1_2*self.width*self.heel_super_unit_load*self.heel_length*(self.length - _1_2*self.heel_length),
            # Footing weight moment
            _1_2*self.weight*self.length,
        )
        return sum(mr)

    @cached_property
    def reaction_offset_from_toe(self) -> float:
        return (self.resisting_moment - self.overturning_moment)/self.total_weight

    @cached_property
    def eccentricity(self) -> float:
        return _1_2*self.length - self.reaction_offset_from_toe

    @cached_property
    def relative_eccentricity(self) -> float:
        return self.eccentricity/self.length

    @cached_property
    def outside_middle_third(self) -> bool:
        return abs(self.relative_eccentricity) > _1_6

    @cached_property
    def outside_footing(self) -> bool:
        return abs(self.relative_eccentricity) > _1_2

    """'''''''''''''"""
    """   METHODS   """
    """'''''''''''''"""

    """'''''''''''''''''''"""
    """   CLASS METHODS   """
    """'''''''''''''''''''"""

    @classmethod
    def optimize(
            cls,
            toe_length: float|Iterable[float],
            heel_length: float|Iterable[float],
            height: float|Iterable[float],
            width: float|Iterable[float],
            bearing_length: float,
            overturning_moment: float,
            superimposed_load: float = 0,
            allow_bearing_pressure: float = 1500.0,
            min_safety_factor: float = 1.5,
            toe_super_unit_load: float = 0.0,
            heel_super_unit_load: float = 0.0,
            unit_weight: float = 150.0,
            force_centered: bool = False,
            max_iterations: int = 3,
            max_samples: int = 100,
    ) -> "Overturning":
        """
        Find optimum footing dimensions for given design criteria.

        *Note:* Assumes consistent units. If units other than feet and pounds
        are used, ``allow_bearing_pressure`` and ``gamma_c`` must be provided.

        Minimize footing volume subject to the dimensional bounds, stability
        criteria, and allowable bearing pressure provided.

        Parameters
        ----------
        toe_length: float or Iterable[float]
            Toe length bounds.
        heel_length: float or Iterable[float]
            Heel length bounds.
        height: float or Iterable[float]
            Footing height bounds.
        width: float or Iterable[float]
            Footing width bounds.
        bearing_length: float
            Length of bearing on footing (e.q., stem thickness or pier depth).
        overturning_moment: float
            Overturning moment on footing.
        superimposed_load: float
            Lineal load on footing including stem, pier, etc.
        allow_bearing_pressure: float
            Allowable bearing pressure. Defaults to ``1500.0``.
        min_safety_factor: float
            Minimum allowable safety factor. Defaults to ``1.5``.
        toe_super_unit_load: float
            Overburden pressure on toe. Defaults to ``0.0``.
        heel_super_unit_load: float
            Overburden pressure on heel. Defaults to ``0.0``.
        unit_weight: float
            Concrete unit weight. Defaults to ``150.0``.
        force_centered: bool
            Force the footing to be centered. Defaults to ``False``.
        max_iterations: int
            Maximum solution space sampling iterations. Used by
            ``scipy.optimize.shgo``. Defaults to ``3``.
        max_samples: int
            Maximum solution space samples. Used by
            ``scipy.optimize.shgo``. Defaults to ``100``.

        Returns
        -------
        result : Overturning
            Result of the optimization.
        """
        toe_length, heel_length, height, width = \
            parse_as_ndarray(toe_length, heel_length, height, width, scalar_dims=1)

        # boundary (geometry) constraints
        bounds = cls._make_bounds(toe_length, heel_length, height, width)  # pyright: ignore[reportArgumentType]
        if all(np.isclose(bounds.ub - bounds.lb, 0.0)):
            return cls(
                toe_length=float(bounds.lb[0]),
                heel_length=float(bounds.lb[1]),
                height=float(bounds.lb[2]),
                width=float(bounds.lb[3]),
                bearing_length=bearing_length,
                overturning_moment=overturning_moment,
                superimposed_load=superimposed_load,
                toe_super_unit_load=toe_super_unit_load,
                heel_super_unit_load=heel_super_unit_load,
                unit_weight=unit_weight
            )

        # partial design functions
        fkwargs = {
            "l_brg": bearing_length,
            "M_ot": overturning_moment,
            "W": superimposed_load,
            "w_t": toe_super_unit_load,
            "w_h": heel_super_unit_load,
            "gamma_c": unit_weight
        }

        fS = (lambda X:
            cls.calc_stability(X[0], X[1], h=X[2], b=X[3], **fkwargs) - min_safety_factor)

        fB = (lambda X:
            allow_bearing_pressure - cls.calc_bearing(X[0], X[1], h=X[2], b=X[3], **fkwargs)[0])

        fCtr = lambda X: -(X[0]-X[1])**2

        fObjective = lambda X: (X[0]+X[1]+bearing_length)*X[2]*X[3] # Volume

        # nonlinear (stability, bearing) constraints
        if force_centered:
            constraints = (
                {'type': 'ineq', 'fun': fS},
                {'type': 'ineq', 'fun': fB},
                {'type': 'ineq', 'fun': fCtr}
            )
        else:
            constraints = (
                {'type': 'ineq', 'fun': fS},
                {'type': 'ineq', 'fun': fB}
            )

        solution = scipy_shgo( # type: ignore
            func=fObjective,
            bounds=bounds,
            constraints=constraints,  # pyright: ignore[reportArgumentType]
            n=max_samples,
            iters=max_iterations,
        )

        if solution.success:
            return cls(
                toe_length=float(solution.x[0]),
                heel_length=float(solution.x[1]),
                height=float(solution.x[2]),
                width=float(solution.x[3]),
                bearing_length=bearing_length,
                overturning_moment=overturning_moment,
                superimposed_load=superimposed_load,
                toe_super_unit_load=toe_super_unit_load,
                heel_super_unit_load=heel_super_unit_load,
                unit_weight=unit_weight,
                optimize_solution=solution
            )
        else:
            return cls(
                toe_length=float(bounds.lb[0]) if bounds.lb[0] == bounds.ub[0] else np.nan,
                heel_length=float(bounds.lb[1]) if bounds.lb[1] == bounds.ub[1] else np.nan,
                height=float(bounds.lb[2]) if bounds.lb[2] == bounds.ub[2] else np.nan,
                width=float(bounds.lb[3]) if bounds.lb[3] == bounds.ub[3] else np.nan,
                bearing_length=bearing_length,
                overturning_moment=overturning_moment,
                superimposed_load=superimposed_load,
                toe_super_unit_load=toe_super_unit_load,
                heel_super_unit_load=heel_super_unit_load,
                unit_weight=unit_weight,
                optimize_solution=solution
            )

    """''''''''''''''''''''"""
    """   STATIC METHODS   """
    """''''''''''''''''''''"""

    @staticmethod
    def calc_stability(
        l_t: float,
        l_h: float,
        l_brg: float,
        h: float,
        b: float,
        M_ot: float,
        W: float,
        w_t: float,
        w_h: float,
        gamma_c: float,
    ) -> float:
        """
        Compute the overturning safety factor for a footing.

        Parameters
        ----------
        l_t: float
            Toe length.
        l_h: float
            Heel length.
        l_brg: float
            Load bearing length.
        h: float
            Footing height.
        b: float
            Footing width.
        M_ot: float
            Overturning moment.
        W: float
            Lineal load applied to footing.
        w_t: float
            Superimposed area load on toe of footing.
        w_h: float
            Superimposed area load on heel of footing.
        gamma_c: float
            Unit weight of concrete.

        Returns
        -------
        float
            Calculated Safety Factor
        """
        l = l_t + l_h + l_brg # total footing length

        # return infinite safety factor if M_ot is nearly zero
        if np.isclose(M_ot, 0.0):
            return np.inf

        M_r = (
            _1_2*b*w_t*l_t**2 +                       # toe surcharge
            W*(l_t + _1_2*l_brg) +                    # load
            _1_2*b*w_h*l_h*(l_t + l_brg + _1_2*l_h) + # heel surcharge
            _1_2*b*gamma_c*h*l**2                     # footing weight
        )

        return M_r/M_ot

    @staticmethod
    def calc_bearing(
            l_t: float,
            l_h: float,
            l_brg: float,
            h: float,
            b: float,
            M_ot: float,
            W: float,
            w_t: float,
            w_h: float,
            gamma_c: float,
    ) -> tuple[float, float]:
        """
        Compute the maximum and minimum bearing pressures.

        *Assumes consistent units.*

        Parameters
        ----------
        l_t: float
            Toe length.
        l_h: float
            Heel length.
        l_brg: float
            Load bearing length.
        h: float
            Footing height.
        b: float
            Footing width.
        M_ot: float
            Overturning moment.
        W: float
            Lineal load applied to footing.
        w_t: float
            Superimposed area load on toe of footing.
        w_h: float
            Superimposed area load on heel of footing.
        gamma_c: float
            Unit weight of concrete.

        Returns
        -------
        float, float
            Maximum and minimum bearing pressure.
        """
        l = l_t + l_h + l_brg
        s = _1_6 * l**2

        # Total Downwards Load
        N = (b*l_t*w_t +    # toe surcharge
            W +            # load
            b*l_h*w_h +    # heel surcharge
            gamma_c*b*l*h) # footing weight

        # Resisting Moment
        M_r = (_1_2*b*w_t*l_t**2 +             # toe surcharge
            W*(l_t + _1_2*l_brg) +          # load
            _1_2*b*w_h*l_h*(l - _1_2*l_h) + # heel surcharge
            _1_2*gamma_c*b*h*l**2)          # footing weight

        x0 = (M_r - M_ot)/N # Distance from toe to reaction.
        ecc = _1_2*l - x0   # Eccentricity from footing centerline.

        if x0 < 0:
            return np.inf, -np.inf

        if np.abs(ecc) > _1_6:
            return _2_3*N/x0, 0

        return N/l + np.abs(M_r - M_ot)/s, N/l - np.abs(M_r - M_ot)/s

    """''''''''''''''''''''''"""
    """  PROTECTED METHODS   """
    """''''''''''''''''''''''"""

    @staticmethod
    def _make_bounds(
            l_t: np.ndarray,
            l_h: np.ndarray,
            h: np.ndarray,
            b: np.ndarray,
    ) -> Bounds:
        bmin, bmax = list[float](), list[float]()

        for pi in (l_t, l_h, h, b):
            if pi.size == 1:
                bmin.append(float(pi.item()))
                bmax.append(float(pi.item()))
            elif pi.size > 1:
                bmin.append(pi.min())
                bmax.append(pi.max())
            else:
                bmin.append(np.nan)
                bmax.append(np.nan)

        return Bounds(lb=bmin, ub=bmax)
